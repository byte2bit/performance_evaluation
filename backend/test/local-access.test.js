test('driver query interception refuses SQL before execution and records only operation/table metadata', async () => {
    const audit = [], executed = [], connection = { query(options, callback) { executed.push(options.sql); callback(null, []); return new EventEmitter() } }
    guardConnection(connection, audit)
    await new Promise((resolve, reject) => connection.query('SELECT * FROM ??.?? WHERE id=?', [TARGET, fixtures.users2, 7], error => error ? reject(error) : resolve()))
    await new Promise(resolve => connection.query('UPDATE users2 SET active=1', error => { assert.equal(error.code, 'E2B_FIXTURE_SQL_REFUSED'); resolve() }))
    assert.equal(executed.length, 1)
    assert.deepEqual(audit, [{ kind: 'select', tables: [fixtures.users2] }, { kind: 'blocked', tables: [] }])
    assert.equal(JSON.stringify(audit).includes(stored), false)
})

