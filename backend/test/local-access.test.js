test('copy exclusivity guards refuse competing sessions, metadata locks or a lost advisory lock without killing clients', async () => {
    for (const issue of ['session', 'metadata', 'advisory']) {
        const queries = [], db = { async query(sql) {
            queries.push(sql)
            if (sql.includes('metadata_locks')) return [issue === 'metadata' ? [{ id: 99 }] : []]
            if (sql.includes('threads')) return [[{ id: 41, db: TARGET }, ...(issue === 'session' ? [{ id: 99, db: TARGET }] : [])]]
            return [[{ id: issue === 'advisory' ? 99 : 41 }]]
        } }
        await assert.rejects(assertControl(db, new Set([41])))
        assert.ok(queries.every(sql => sql.startsWith('SELECT')))
    }
})

