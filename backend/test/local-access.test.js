function activationDb({ changedIdentity = false, failId, failCommit = false } = {}) {
    let rows = accounts(), saved, began = 0, rolledBack = 0, committed = 0
    const queries = []
    return {
        expected: accounts(), queries,
        db: {
            async beginTransaction() { began++; saved = structuredClone(rows) },
            async rollback() { rows = saved; rolledBack++ },
            async commit() { if (failCommit) throw new Error('synthetic commit failure'); committed++ },
            async query(sql, bindings) {
                queries.push({ sql, bindings })
                assert.equal(bindings[0], TARGET)
                if (sql.startsWith('SELECT')) { const result = structuredClone(rows); if (changedIdentity) result[0].name = 'changed'; return [result] }
                assert.match(sql, /^UPDATE \?\?\.users2 SET active=1,session_version=1/)
                assert.match(sql, /BINARY password=\? AND admin=\? AND deletedAt IS NULL$/)
                const row = rows.find(row => row.id === bindings[1])
                assert.equal(row.password, bindings[2]); assert.equal(row.admin, bindings[3])
                if (row.id === failId) return [{ affectedRows: 0 }]
                row.active = 1; row.session_version = 1; return [{ affectedRows: 1 }]
            }
        },
        get state() { return { rows, began, rolledBack, committed } }
    }
}

test('activation rehearses rollback and commits exactly active/version for all 25 accounts, preserving every hash/field', async () => {
    const h = activationDb()
    assert.equal(await activateAccounts(h.db, h.expected, true), 25)
    assert.deepEqual(h.state.rows, h.expected); assert.equal(h.state.rolledBack, 1)
    assert.equal(await activateAccounts(h.db, h.expected, false), 25)
    assert.deepEqual(h.state.rows, h.expected.map(row => ({ ...row, active: 1, session_version: 1 })))
    assert.equal(h.state.committed, 1)
    assert.equal(h.queries.filter(row => row.sql.startsWith('UPDATE')).length, 50)
})

test('map changes, one failed conditional update and commit failure rollback without partial activation', async () => {
    for (const options of [{ changedIdentity: true }, { failId: 10 }, { failCommit: true }]) {
        const h = activationDb(options)
        await assert.rejects(activateAccounts(h.db, h.expected, false))
        assert.deepEqual(h.state.rows, h.expected); assert.equal(h.state.rolledBack, 1); assert.equal(h.state.committed, 0)
    }
})

test('cleanup refuses unknown names, uncreated fixtures or ownership mismatch before DROP', async () => {
    const runId = 'b'.repeat(32), queries = []
    const db = { async query(sql, bindings) { queries.push({ sql, bindings }); return [[{ marker: 'evaluation-e2b:' + runId, engine: 'InnoDB' }]] } }
    await assert.rejects(dropOwnedFixture(db, 'users2', runId, new Set(['users2'])))
    await assert.rejects(dropOwnedFixture(db, fixtures.users2, runId, new Set()))
    assert.equal(queries.length, 0)
    const wrong = { async query() { return [[{ marker: 'other-run', engine: 'InnoDB' }]] } }
    await assert.rejects(dropOwnedFixture(wrong, fixtures.users2, runId, new Set([fixtures.users2])))
    const owned = new Set([fixtures.users2])
    await dropOwnedFixture(db, fixtures.users2, runId, owned)
    assert.equal(owned.size, 0)
    assert.deepEqual(queries.at(-1), { sql: 'DROP TABLE ??.??', bindings: [TARGET, fixtures.users2] })
})
